"""ziro-shell — plugins.gen.zsh generator (Schema C).

Layer: 3 (znap Runtime)
Spec: 002 (load order) + Spec 003 (Schema C)
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
import os
from pathlib import Path

from core.models import Strategy
from core.resolver import ResolvedConfig
from core.ziro_load import LoadSpec, emit, from_resolved


HEADER_LINE = "# AUTO-GENERATED by ziro — do not edit"
SCHEMA_VERSION = "0.1.0"


# Fixed load order per Spec 002 R3
LOAD_ORDER = [
    "zsh-completions",   # 1. Eager, before compinit
    "ohmyzsh-git",       # 2. Eager, compdef
    "# compinit",        # 3. Marker
    "starship",          # 4. Eval-cache
    "fzf",               # 5. Eval-cache
    "ziro-ghost",        # 6. Ziro-defer
    "fast-syntax-highlighting",  # 7. Ziro-defer
    "zcolors",           # 8. Eval-cache
    "zoxide",            # 9. Eval-cache
    "ohmyzsh-colored-man-pages",  # 10. Ziro-defer
]


@dataclass(frozen=True)
class EmitOptions:
    """Options for generator."""
    enforce_order: bool = True
    generated_at: str = ""
    ziro_home: Path | None = None


def _resolve_plugin_target(plugin: str, pick: str = "", ziro_home: Path | None = None) -> tuple[str, bool]:
    """Detect if plugin is a local clone in plugins/.

    Returns (target_string, is_local).
    """
    if plugin.startswith(("$ZIRO_HOME/", "~/.ziro/", "plugins/")):
        return plugin, True

    zh = ziro_home or Path(os.environ.get("ZIRO_HOME", Path.home() / ".ziro"))
    pdir = zh / "plugins" / plugin
    if not pdir.is_dir():
        rel_pdir = Path("plugins") / plugin
        if rel_pdir.is_dir():
            pdir = rel_pdir
        else:
            return plugin, False

    # It's a local plugin in plugins/<plugin>
    if pick and (pdir / pick).is_file():
        return f"$ZIRO_HOME/plugins/{plugin}/{pick}", True

    cand = pdir / f"{plugin}.plugin.zsh"
    if cand.is_file():
        return f"$ZIRO_HOME/plugins/{plugin}/{cand.name}", True

    named = list(pdir.glob(f"**/{plugin}.plugin.zsh"))
    if named:
        rel = named[0].relative_to(pdir)
        return f"$ZIRO_HOME/plugins/{plugin}/{rel}", True

    cand_zsh = pdir / f"{plugin}.zsh"
    if cand_zsh.is_file():
        return f"$ZIRO_HOME/plugins/{plugin}/{cand_zsh.name}", True

    return f"$ZIRO_HOME/plugins/{plugin}", True


def _emit_plugin(
    plugin: str,
    strategy: str,
    *,
    compile_: bool = True,
    eval_cache: bool = False,
    pick: str = "",
    wait: str = "",
    defer_slot: str = "",
    raw: str = "",
    ziro_home: Path | None = None,
) -> str:
    """Emit zsh line for one plugin via ziro_load."""
    target_plugin, is_local = _resolve_plugin_target(plugin, pick=pick, ziro_home=ziro_home)
    spec = from_resolved(
        plugin=target_plugin,
        strategy=strategy,
        compile_=compile_,
        eval_cache=eval_cache,
        pick="" if is_local else pick,
        wait=wait,
        defer_slot=defer_slot,
        raw=raw,
        is_local=is_local,
    )
    return emit(spec)


def generate(
    configs: list,  # list[ResolvedConfig]
    output_path: Path,
    *,
    options: EmitOptions | None = None,
) -> Path:
    """Write plugins.gen.zsh (Schema C). Deterministic for same input."""
    opts = options or EmitOptions()
    ts = opts.generated_at or datetime.now(timezone.utc).isoformat()

    # Sort configs by load order if requested
    ordered = list(configs)
    if opts.enforce_order:
        def order_key(cfg):
            try:
                if cfg.plugin in LOAD_ORDER:
                    return LOAD_ORDER.index(cfg.plugin)
                if cfg.plugin == "git" and "ohmyzsh-git" in LOAD_ORDER:
                    return LOAD_ORDER.index("ohmyzsh-git")
                return len(LOAD_ORDER)
            except ValueError:
                return len(LOAD_ORDER)  # unknown → end
        ordered = sorted(configs, key=order_key)

    lines: list[str] = [
        HEADER_LINE,
        f"# Schema: {SCHEMA_VERSION}",
        f"# Generated: {ts}",
        "",
    ]

    for cfg in ordered:
        line = _emit_plugin(
            plugin=cfg.plugin,
            strategy=cfg.strategy.value if hasattr(cfg.strategy, "value") else str(cfg.strategy),
            compile_=getattr(cfg, "compile", True),
            eval_cache=getattr(cfg, "eval_cache", False),
            pick=getattr(cfg, "pick", ""),
            wait=getattr(cfg, "wait", ""),
            defer_slot=getattr(cfg, "defer_slot", ""),
            raw=getattr(cfg, "raw", ""),
            ziro_home=opts.ziro_home,
        )
        lines.append(line)

    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines))
    return output_path


def generate_plugins_gen(
    config_dir: Path,
    ziro_home: Path | None = None,
) -> Path:
    """Generate ~/.config/ziro/derived/plugins.gen.zsh from defaults.toml and installed plugins.

    Implements Spec 001 FR-006a (materialized at generation time) and Spec 004 R1 (load order).
    """
    zh = ziro_home or Path(os.environ.get("ZIRO_HOME", Path.home() / ".ziro"))
    configs: list[ResolvedConfig] = []

    # 1. Parse defaults from defaults.toml (or fallback to Spec 004 R1 defaults)
    defaults_file = config_dir / "defaults.toml"
    defaults_data: dict = {}
    if defaults_file.is_file():
        try:
            import tomllib
            with defaults_file.open("rb") as f:
                defaults_data = tomllib.load(f)
        except Exception:
            pass

    # Prompt
    prompt_val = defaults_data.get("prompt", {}).get("default", "starship")
    pconf = config_dir / "prompt.conf"
    if pconf.is_file():
        try:
            prompt_val = pconf.read_text(encoding="utf-8").strip() or prompt_val
        except OSError:
            pass
    if prompt_val == "starship":
        configs.append(
            ResolvedConfig(
                plugin="starship",
                strategy=Strategy.EAGER,
                eval_cache=True,
                raw="(( $+commands[starship] )) && znap eval starship 'starship init zsh --print-full-init'",
            )
        )

    # Completions (before compinit)
    comp_val = defaults_data.get("completions", {}).get("default", "zsh-completions")
    if comp_val != "none":
        configs.append(
            ResolvedConfig(
                plugin="zsh-completions",
                strategy=Strategy.EAGER,
                raw="znap source zsh-users/zsh-completions",
            )
        )

    # Fuzzy finder
    fzf_val = defaults_data.get("fuzzy_finder", {}).get("default", "fzf")
    if fzf_val != "none":
        configs.append(
            ResolvedConfig(
                plugin="fzf",
                strategy=Strategy.EAGER,
                eval_cache=True,
                raw="(( $+commands[fzf] )) && znap eval fzf 'fzf --zsh'",
            )
        )

    # Auto suggest
    suggest_val = defaults_data.get("auto_suggest", {}).get("default", "ziro-ghost")
    if suggest_val == "ziro-ghost":
        configs.append(
            ResolvedConfig(
                plugin="ziro-ghost",
                strategy=Strategy.AFTER_PROMPT,
                raw="ziro-defer source $ZIRO_HOME/ghost/ghost.zsh",
            )
        )
    elif suggest_val == "zsh-autosuggestions":
        configs.append(
            ResolvedConfig(
                plugin="zsh-autosuggestions",
                strategy=Strategy.AFTER_PROMPT,
                raw="ziro-defer znap source zsh-users/zsh-autosuggestions",
            )
        )

    # Syntax highlighting
    syn_val = defaults_data.get("syntax_highlighting", {}).get("default", "fast-syntax-highlighting")
    if syn_val == "fast-syntax-highlighting":
        configs.append(
            ResolvedConfig(
                plugin="fast-syntax-highlighting",
                strategy=Strategy.AFTER_PROMPT,
                raw="ziro-defer znap source zdharma-continuum/fast-syntax-highlighting",
            )
        )
    elif syn_val == "zsh-syntax-highlighting":
        configs.append(
            ResolvedConfig(
                plugin="zsh-syntax-highlighting",
                strategy=Strategy.AFTER_PROMPT,
                raw="ziro-defer znap source zsh-users/zsh-syntax-highlighting",
            )
        )

    # Colors (Zsh plugin, not external binary)
    colors_val = defaults_data.get("colors", {}).get("default", "zcolors")
    if colors_val == "zcolors":
        configs.append(
            ResolvedConfig(
                plugin="zcolors",
                strategy=Strategy.AFTER_PROMPT,
                raw="ziro-defer znap source marlonrichert/zcolors",
            )
        )

    # Navigation
    nav_val = defaults_data.get("navigation", {}).get("default", "zoxide")
    if nav_val == "zoxide":
        configs.append(
            ResolvedConfig(
                plugin="zoxide",
                strategy=Strategy.EAGER,
                eval_cache=True,
                raw="(( $+commands[zoxide] )) && znap eval zoxide 'zoxide init zsh'",
            )
        )

    # 2. Add local plugins in $ZIRO_HOME/plugins/
    pdir = zh / "plugins"
    if pdir.is_dir():
        from core.analyzer import analyze_with_cache
        from core.resolver import resolve
        for p in sorted(pdir.iterdir()):
            if p.is_dir() and not p.name.startswith("."):
                try:
                    analysis = analyze_with_cache(p, p.name)
                    configs.append(resolve(analysis, config_dir))
                except Exception:
                    continue

    output_path = default_output_path(config_dir)
    return generate(configs, output_path, options=EmitOptions(enforce_order=True, ziro_home=zh))


def default_output_path(config_dir: Path) -> Path:
    return config_dir / "derived" / "plugins.gen.zsh"


