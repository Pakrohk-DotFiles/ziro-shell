"""ziro-shell — shell completion generator.

Layer: 3 (Python core)
Spec: 008 R10, SC-1, SC-2
"""

from __future__ import annotations

import sys
from typing import Any
from core.help_cli import HELP_REGISTRY


def get_completion_data() -> dict[str, Any]:
    """Extract structured command, subcommand, and flag completion data from HELP_REGISTRY."""
    top_commands: list[tuple[str, str]] = []
    subcommands_map: dict[str, list[tuple[str, str]]] = {}
    flags_map: dict[str, list[tuple[str, str]]] = {}

    for name, entry in HELP_REGISTRY.items():
        if " " not in name:
            top_commands.append((name, entry.summary))
            if entry.subcommands:
                subcommands_map[name] = [
                    (sub, desc) for sub, desc in entry.subcommands.items()
                ]
            if entry.flags:
                flags_map[name] = [(f[0], f[1]) for f in entry.flags]
        else:
            # Subcommand entry, e.g. "plugin add"
            if entry.flags:
                flags_map[name] = [(f[0], f[1]) for f in entry.flags]

    top_commands.sort(key=lambda x: x[0])
    return {
        "commands": top_commands,
        "subcommands": subcommands_map,
        "flags": flags_map,
    }


def _escape_zsh_desc(desc: str) -> str:
    """Escape brackets and colons for zsh _describe / _arguments."""
    return desc.replace(":", "\\:").replace("[", "\\[").replace("]", "\\]").replace("'", "'\\''")


def generate_zsh_completion() -> str:
    """Generate a self-contained Zsh completion script for ziro."""
    data = get_completion_data()
    lines: list[str] = [
        "#compdef ziro",
        "# ─── ziro zsh completion script ───",
        "# Auto-generated by: ziro completion zsh",
        "",
        "_ziro() {",
        "  local curcontext=\"$curcontext\" state line",
        "  typeset -A opt_args",
        "",
        "  _arguments -C \\",
        "    '(-h --help)'{-h,--help}'[Show help information]' \\",
        "    '(-v --version)'{-v,--version}'[Show version]' \\",
        "    '1: :->command' \\",
        "    '*:: :->args'",
        "",
        "  case $state in",
        "    command)",
        "      local -a commands",
        "      commands=(",
    ]

    for cmd, desc in data["commands"]:
        esc = _escape_zsh_desc(desc)
        lines.append(f"        '{cmd}:{esc}'")

    lines.extend([
        "      )",
        "      _describe -t commands 'ziro command' commands",
        "      ;;",
        "    args)",
        "      case $line[1] in",
    ])

    # Generate handlers for commands with subcommands or flags
    for cmd, desc in data["commands"]:
        subs = data["subcommands"].get(cmd, [])
        if subs:
            lines.extend([
                f"        {cmd})",
                f"          _ziro_{cmd}",
                "          ;;",
            ])
        else:
            # Command without subcommands, e.g. install, doctor, bench
            cmd_flags = data["flags"].get(cmd, [])
            lines.extend([
                f"        {cmd})",
                "          _arguments \\",
            ])
            for flag, fdesc in cmd_flags:
                flag_clean = flag.split()[0]  # Take flag name
                esc_desc = _escape_zsh_desc(fdesc)
                lines.append(f"            '{flag_clean}[{esc_desc}]' \\")
            lines.extend([
                "            '(-h --help)'{-h,--help}'[Show help information]'",
                "          ;;",
            ])

    lines.extend([
        "      esac",
        "      ;;",
        "  esac",
        "}",
        "",
    ])

    # Generate helper functions for subcommands
    for cmd, subs in data["subcommands"].items():
        lines.extend([
            f"_ziro_{cmd}() {{",
            "  local curcontext=\"$curcontext\" state line",
            "  typeset -A opt_args",
            "",
            "  _arguments -C \\",
            "    '(-h --help)'{-h,--help}'[Show help information]' \\",
            "    '1: :->subcommand' \\",
            "    '*:: :->subargs'",
            "",
            "  case $state in",
            "    subcommand)",
            "      local -a subcommands",
            "      subcommands=(",
        ])
        for sub, sdesc in subs:
            esc = _escape_zsh_desc(sdesc)
            lines.append(f"        '{sub}:{esc}'")
        lines.extend([
            "      )",
            f"      _describe -t subcommands '{cmd} subcommand' subcommands",
            "      ;;",
            "    subargs)",
            "      case $line[1] in",
        ])
        for sub, sdesc in subs:
            full_sub = f"{cmd} {sub}"
            sub_flags = data["flags"].get(full_sub, [])
            lines.extend([
                f"        {sub})",
                "          _arguments \\",
            ])
            for flag, fdesc in sub_flags:
                flag_clean = flag.split()[0]
                esc_desc = _escape_zsh_desc(fdesc)
                lines.append(f"            '{flag_clean}[{esc_desc}]' \\")
            lines.extend([
                "            '(-h --help)'{-h,--help}'[Show help information]'",
                "          ;;",
            ])
        lines.extend([
            "      esac",
            "      ;;",
            "  esac",
            "}",
            "",
        ])

    lines.extend([
        "if (( $+functions[compdef] )); then",
        "  compdef _ziro ziro",
        "fi",
        "",
        '_ziro "$@"',
        "",
    ])

    return "\n".join(lines)


def cmd_completion(argv: list[str] | None = None) -> int:
    """Entry point for `ziro completion [shell]`."""
    from core.help_cli import handle_help_if_requested
    ret = handle_help_if_requested(argv, "completion")
    if ret is not None:
        return ret

    args = [a for a in (argv or []) if not a.startswith("-")]
    shell = args[0] if args else "zsh"

    if shell != "zsh":
        print(f"ziro completion: unsupported shell '{shell}'. Supported: zsh", file=sys.stderr)
        return 1

    print(generate_zsh_completion())
    return 0


def main(argv: list[str]) -> int:
    return cmd_completion(argv)


__all__ = ["cmd_completion", "generate_zsh_completion", "get_completion_data", "main"]
