DEFAULT_THEME = "lambda"
_HEADER = "# Generated by ziro theme"


def language_segments(enabled: dict[str, bool]) -> str:
    """Render the language module segment string from ENABLE_* flags."""
    return "".join(
        module for key, module in SEGMENT_MODULES.items() if enabled.get(key)
    )


def enabled_from_env(get_flag) -> dict[str, bool]:
    """Build the enabled map using a callable returning the flag value."""
    return {key: bool(get_flag(key)) for key in SEGMENT_MODULES}


def marker(enabled: dict[str, bool]) -> str:
    return " ".join(
        f"{key.removeprefix('ENABLE_').lower()}={'on' if enabled.get(key) else 'off'}"
        for key in SEGMENT_MODULES
    )


def render(name: str, enabled: dict[str, bool]) -> str:
    theme = THEMES[name]
    body = theme["template"].replace("@LANG_TOML@", LANG_MODULE_TOML)
    return (body
            .replace("@SEGMENTS@", language_segments(enabled))
            .replace("@NAME@", name)
            .replace("@MARKER@", marker(enabled)))


def is_managed(path) -> bool:
    """True if the file was generated by us (safe to overwrite)."""
    try:
        return _HEADER in path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
