"""Built-in Starship prompt themes.

A theme is a raw starship.toml template with two @-placeholders:
  @SEGMENTS@  -> language modules derived from ENABLE_* flags (apply time;
                 re-run `ziro theme apply` after changing language flags)
  @NAME@      -> theme name (for the generated-by header marker)

Re-applying a theme overwrites the file only when it carries our marker,
so user-customized configs are never touched.
"""

